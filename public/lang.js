  function getLang() {
    if (SUPPORTED_LANGS.includes(activeLang)) return activeLang;
    const saved = String(localStorage.getItem(LANG_KEY) || localStorage.getItem(LEGACY_LANG_KEY) || "ru").trim().toLowerCase();
    return SUPPORTED_LANGS.includes(saved) ? saved : "ru";
  }

  function setLang(lang, options = {}) {
    const next = SUPPORTED_LANGS.includes(lang) ? lang : "ru";
    activeLang = next;
    if (!options.transient) {
      localStorage.setItem(LANG_KEY, next);
      localStorage.setItem(LEGACY_LANG_KEY, next);
      if (options.manual !== false) localStorage.setItem(`${LANG_KEY}_manual`, "1");
    }
    document.documentElement.lang = next;
    syncSelectValue(next);
    applyTranslations();
    window.dispatchEvent(new CustomEvent("asking:languagechange", { detail: { lang: next, manual: options.manual !== false, transient: Boolean(options.transient) } }));
  }

  function syncSelectValue(lang) {
    document.querySelectorAll(`#${SELECT_ID}, .asking-lang-select`).forEach((node) => {
      if (node instanceof HTMLSelectElement) node.value = lang;
    });
    const localeSelect = document.getElementById("localeSelect");
    if (localeSelect instanceof HTMLSelectElement && SUPPORTED_LANGS.includes(lang)) {
      localeSelect.value = lang;
    }
  }

  function translateExact(value, lang) {
    if (!value) return value;
    return exactText[lang]?.[value] || value;
  }

  function translatePattern(value, lang) {
    if (!value || lang === "ru") return value;
    const list = patternText[lang] || [];
    for (const [pattern, replacement] of list) {
      if (pattern.test(value)) return value.replace(pattern, replacement);
    }
    return value;
  }

  function translateValue(value, lang) {
    return translatePattern(translateExact(value, lang), lang);
  }

  function translateTextNode(node, lang) {
    const raw = textSourceCache.has(node) ? textSourceCache.get(node) : node.nodeValue;
    if (!raw || !raw.trim()) return;
    if (!textSourceCache.has(node)) textSourceCache.set(node, raw);
    const leading = raw.match(/^\s*/)?.[0] || "";
    const trailing = raw.match(/\s*$/)?.[0] || "";
    const core = raw.trim();
    const next = translateValue(core, lang);
    if (next !== core) node.nodeValue = `${leading}${next}${trailing}`;
    else if (node.nodeValue !== raw) node.nodeValue = raw;
  }

  function translateAttributes(lang) {
    document.querySelectorAll("[title], [aria-label], input[type='button'], input[type='submit']").forEach((node) => {
      let source = attributeSourceCache.get(node);
      if (!source) {
        source = {
          title: node.getAttribute("title"),
          ariaLabel: node.getAttribute("aria-label"),
          value: node instanceof HTMLInputElement ? node.value : null
        };
        attributeSourceCache.set(node, source);
      }

      if (source.title != null) {
        node.setAttribute("title", lang === "ru" ? source.title : translateValue(source.title, lang));
      }
      if (source.ariaLabel != null) {
        node.setAttribute("aria-label", lang === "ru" ? source.ariaLabel : translateValue(source.ariaLabel, lang));
      }
      if (source.value != null && node instanceof HTMLInputElement) {
        node.value = lang === "ru" ? source.value : translateValue(source.value, lang);
      }
    });

    document.querySelectorAll("option").forEach((node) => {
      if (node.closest("[data-no-i18n]")) return;
      const raw = textSourceCache.has(node) ? textSourceCache.get(node) : node.textContent;
      if (!raw || !raw.trim()) return;
      if (!textSourceCache.has(node)) textSourceCache.set(node, raw);
      node.textContent = lang === "ru" ? raw : translateValue(raw.trim(), lang);
    });
  }

  function startObserver() {
    if (!observer || !document.body) return;
    observer.disconnect();
    observer.observe(document.body, {
      childList: true,
      subtree: true
    });
  }

  function applyTranslations() {
    const lang = getLang();
    document.documentElement.lang = lang;
    isApplying = true;
    if (observer) observer.disconnect();

    if (!titleSourceCache.value) titleSourceCache.value = document.title;
    const baseTitle = titleSourceCache.value;
    if (lang === "ru") {
      document.title = baseTitle;
    } else {
      document.title = titleText[lang]?.[baseTitle] || baseTitle;
    }

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walker.nextNode()) {
      const parent = walker.currentNode.parentElement;
      if (!parent) continue;
      if (["SCRIPT", "STYLE", "TEXTAREA", "OPTION"].includes(parent.tagName)) continue;
      if (parent.closest("[data-no-i18n]")) continue;
      textNodes.push(walker.currentNode);
    }
    textNodes.forEach((node) => translateTextNode(node, lang));

    document.querySelectorAll("input[placeholder], textarea[placeholder]").forEach((node) => {
      const original = placeholderSourceCache.has(node)
        ? placeholderSourceCache.get(node)
        : node.getAttribute("placeholder");
      if (!original) return;
      if (!placeholderSourceCache.has(node)) placeholderSourceCache.set(node, original);
      const translated = lang === "ru" ? original : placeholderText[lang]?.[original] || translateValue(original, lang);
      node.setAttribute("placeholder", translated);
    });

    translateAttributes(lang);

    isApplying = false;
    startObserver();
  }

  function buildSelect(lang) {
    const select = document.createElement("select");
    select.id = SELECT_ID;
    select.className = "lang-select asking-lang-select";
    select.setAttribute("aria-label", "Language");
    select.innerHTML = `
      <option value="ru">RU</option>
      <option value="en">EN</option>
      <option value="kz">KZ</option>
    `;
    select.value = lang;
    select.addEventListener("change", () => setLang(select.value));
    return select;
  }

  function ensureSwitcher() {
    const lang = getLang();
    const existing = document.getElementById(SELECT_ID);
    if (existing instanceof HTMLSelectElement) {
      existing.value = lang;
      if (!existing.dataset.langBound) {
        existing.dataset.langBound = "1";
        existing.addEventListener("change", () => setLang(existing.value));
      }
      return;
    }

    const target =
      document.querySelector(".auth-card__top") ||
      document.querySelector(".bv2-topbar__actions") ||
      document.querySelector(".rv2-topbar__actions") ||
      document.querySelector(".svdash-topbar__actions") ||
      document.querySelector(".author-v2-actions") ||
      document.querySelector(".topbar__actions") ||
      document.querySelector(".topbar__inner") ||
      document.querySelector("main");

    if (!target) return;
    target.appendChild(buildSelect(lang));
  }

  function bindLocaleSelect() {
    const localeSelect = document.getElementById("localeSelect");
    if (!(localeSelect instanceof HTMLSelectElement) || localeSelect.dataset.langBound) return;
    localeSelect.dataset.langBound = "1";
    localeSelect.addEventListener("change", () => {
      if (SUPPORTED_LANGS.includes(localeSelect.value)) setLang(localeSelect.value);
    });
  }

  function boot() {
    const initial = getLang();
    activeLang = initial;
    localStorage.setItem(LANG_KEY, initial);
    localStorage.setItem(LEGACY_LANG_KEY, initial);
    ensureSwitcher();
    bindLocaleSelect();
    syncSelectValue(initial);
    applyTranslations();

    observer = new MutationObserver(() => {
      if (isApplying || applyQueued) return;
      applyQueued = true;
      queueMicrotask(() => {
        applyQueued = false;
        if (isApplying) return;
        syncSelectValue(getLang());
        applyTranslations();
      });
    });

    startObserver();
  }

  window.AskingLang = { getLang, setLang, applyTranslations, LANG_KEY, LEGACY_LANG_KEY };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot, { once: true });
  } else {
    boot();
  }
